// Search and share metadata of every page: title, description, Open Graph image and JSON-LD.
// Pages call homeSeo(content, locale) or caseSeo(project, content, locale) and pass the result to Base, which hands it
// to components/seo/Head.astro. Copy lives in src/i18n/<locale>/seo.ts; the facts come only from the site data.
// Person, company and website are one entity in every language (ids at the root); pages and case lists follow the locale.
import type { Project, SiteContent } from './types';
import { featuredProjects } from './content';
import { shortPlatform } from './text';
import { useT, localePath, toLocale, LANG_TAG, LOCALES } from '../i18n';

type T = ReturnType<typeof useT>;

export interface PageSeo {
  title: string;
  description: string;
  /** Share image, absolute or site-relative. Head falls back to the home image. */
  image?: string;
  imageAlt?: string;
  /** Real size of `image`, for og:image:width and og:image:height. */
  imageWidth?: number;
  imageHeight?: number;
  type?: 'website' | 'article' | 'profile';
  /** JSON-LD nodes without @context: Head wraps them in one @graph. */
  jsonLd?: object[];
  noindex?: boolean;
}

/** Default share image, generated by scripts/og-image.mjs (1200 by 630). */
export const DEFAULT_OG = { src: '/og/home.jpg', width: 1200, height: 630 };

const SITE = import.meta.env.SITE;

export function absolute(path: string): string {
  return new URL(path, SITE).href;
}

const ROOT = absolute('/');
const WEBSITE_ID = `${ROOT}#website`;
const PERSON_ID = `${ROOT}#person`;
const ORG_ID = `${ROOT}#organization`;
/** Home of a locale (absolute) and its featured cases list. */
const homeOf = (locale: string | undefined) => absolute(localePath('/', locale));
const casesId = (locale: string | undefined) => `${homeOf(locale)}#cases`;

/** Route of a case page (spec 3.5): /cases/<id>/, under /en/ or /es/ in those locales. */
export function caseUrl(id: string, locale?: string): string {
  return localePath(`/cases/${id}/`, locale);
}

/** Slug the old site used in ?projeto=: title without accents, spaces to hyphens, lowercase (legacy js/functions.js). */
export function legacySlug(title: string): string {
  return title.normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/\s+/g, '-').toLowerCase();
}

function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => values[key] ?? '');
}

type CaseKind = 'migration' | 'landing' | 'liquid' | 'store' | 'site';

/** What kind of work a case is, in search words, from its own data (platform, type, stack). */
function caseKind(project: Project): CaseKind {
  if (/vtex/i.test(`${project.platform} ${project.badge ?? ''} ${project.summary}`)) return 'migration';
  // A site of its own (the previous portfolio, in HTML, CSS and JavaScript) is neither a store nor a platform landing page.
  if (!/Shopify|Yampi|Tray|Nuvemshop|WBuy|WordPress|GreatPages/.test(project.platform)) return 'site';
  if (project.type === 'landing') return 'landing';
  if (project.stack.includes('Liquid')) return 'liquid';
  return 'store';
}

/** Whether the summary already says the kind of work, so the description does not say it twice. */
const KIND_WORD: Partial<Record<CaseKind, RegExp>> = { migration: /vtex/i, landing: /landing page/i };

/** "Name: kind | Lorenzo da Cunha", dropping the brand when the title would be cut in results. */
function withSuffix(title: string, t: T): string {
  const branded = title + t('seo.titleSuffix');
  return branded.length <= 65 ? branded : title;
}

/** First candidate that fits a result snippet (about 160 characters). */
function fitDescription(...candidates: string[]): string {
  return candidates.find((text) => text.length <= 160) ?? candidates[candidates.length - 1];
}

/** The site node. The home also names its publisher (the company in the footer), which only the home describes. */
function website(t: T, withPublisher = false) {
  return {
    '@type': 'WebSite',
    '@id': WEBSITE_ID,
    url: ROOT,
    name: t('seo.siteName'),
    inLanguage: LOCALES.map((l) => LANG_TAG[l]),
    ...(withPublisher ? { publisher: { '@id': ORG_ID } } : {}),
  };
}

function personRef(t: T) {
  return { '@type': 'Person', '@id': PERSON_ID, name: t('seo.siteName'), jobTitle: t('seo.jobTitle'), url: ROOT };
}

/** Topics from the services and every stack in the projects, most used first. */
function knowsAbout(content: SiteContent): string[] {
  const count = new Map<string, number>();
  for (const p of content.projects) for (const s of p.stack) count.set(s, (count.get(s) ?? 0) + 1);
  const stacks = [...count.entries()].sort((a, b) => b[1] - a[1]).map(([name]) => name);
  return [...new Set([...content.services.map((s) => s.title), ...stacks])];
}

function itemList(projects: Project[], t: T, locale: string | undefined) {
  return {
    '@type': 'ItemList',
    '@id': casesId(locale),
    name: t('seo.home.featured'),
    numberOfItems: projects.length,
    itemListElement: projects.map((p, i) => ({ '@type': 'ListItem', position: i + 1, name: p.title, url: absolute(caseUrl(p.id, locale)) })),
  };
}

export function homeSeo(content: SiteContent, locale: string | undefined): PageSeo {
  const t = useT(locale);
  const lang = LANG_TAG[toLocale(locale)];
  const home = homeOf(locale);
  const title = t('seo.home.title');
  const description = t('seo.home.description');
  const image = absolute(DEFAULT_OG.src);
  const { contact, links } = content.profile;
  // Current jobs only (experience.json), e.g. "Aloft." -> Aloft.
  const employers = content.experience.filter((job) => job.current).map((job) => ({ '@type': 'Organization', name: job.where.replace(/\.$/, '') }));

  const person = {
    ...personRef(t),
    description: t('seo.home.personDescription'),
    image: { '@type': 'ImageObject', url: absolute('/assets/brand/retrato.webp'), width: 1000, height: 1000 },
    sameAs: Object.values(links).filter(Boolean),
    knowsAbout: knowsAbout(content),
    // "Americana, SP" in home.facts and the About section.
    address: { '@type': 'PostalAddress', addressLocality: 'Americana', addressRegion: 'SP', addressCountry: 'BR' },
    ...(employers.length ? { worksFor: employers } : {}),
  };

  // The company in the footer: legal name and CNPJ, plus the public contact channels of the site.
  const organization = {
    '@type': 'Organization',
    '@id': ORG_ID,
    name: t('bottom.footer.legalName'),
    legalName: t('bottom.footer.legalName'),
    taxID: t('bottom.footer.cnpj'),
    url: ROOT,
    logo: absolute('/assets/brand/logo-icone.svg'),
    email: contact.email,
    telephone: contact.phoneHref.replace(/^tel:/, ''),
  };

  const profilePage = {
    '@type': 'ProfilePage',
    '@id': `${home}#profilepage`,
    url: home,
    name: title,
    description,
    inLanguage: lang,
    isPartOf: { '@id': WEBSITE_ID },
    mainEntity: { '@id': PERSON_ID },
    primaryImageOfPage: { '@type': 'ImageObject', url: image, width: DEFAULT_OG.width, height: DEFAULT_OG.height },
    hasPart: { '@id': casesId(locale) },
    dateModified: new Date().toISOString(),
  };

  return {
    title,
    description,
    image,
    imageAlt: t('seo.home.imageAlt'),
    imageWidth: DEFAULT_OG.width,
    imageHeight: DEFAULT_OG.height,
    type: 'website',
    jsonLd: [website(t, true), profilePage, person, organization, itemList(featuredProjects(content), t, locale)],
  };
}

export function caseSeo(project: Project, _content: SiteContent, locale: string | undefined): PageSeo {
  const t = useT(locale);
  const lang = LANG_TAG[toLocale(locale)];
  const home = homeOf(locale);
  const url = absolute(caseUrl(project.id, locale));
  const kindKey = caseKind(project);
  const kind = t(`seo.case.kind.${kindKey}`).replace('{platform}', shortPlatform(project.platform));
  const title = withSuffix(fill(t('seo.case.title'), { name: project.title, kind }), t);
  const summary = project.summary.trim();
  const plain = fill(t('seo.case.descriptionPlain'), { summary });
  const full = KIND_WORD[kindKey]?.test(summary) ? plain : fill(t('seo.case.description'), { summary, kind });
  const description = fitDescription(full, plain, summary);
  const cover = project.images[0];
  const platform = shortPlatform(project.platform);

  const work = {
    '@type': 'CreativeWork',
    '@id': `${url}#work`,
    name: project.title,
    description: summary,
    url,
    inLanguage: lang,
    ...(project.images.length
      ? { image: project.images.map((img) => ({ '@type': 'ImageObject', url: absolute(img.src), width: img.width, height: img.height, caption: img.alt })) }
      : {}),
    creator: { '@id': PERSON_ID },
    ...(project.stack.length ? { keywords: project.stack.join(', ') } : {}),
    ...(platform ? { about: { '@type': 'Thing', name: platform } } : {}),
    isPartOf: { '@id': WEBSITE_ID },
  };

  const breadcrumb = {
    '@type': 'BreadcrumbList',
    '@id': `${url}#breadcrumb`,
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: t('seo.breadcrumb.home'), item: home },
      { '@type': 'ListItem', position: 2, name: t('seo.breadcrumb.cases'), item: casesId(locale) },
      { '@type': 'ListItem', position: 3, name: project.title, item: url },
    ],
  };

  const page = {
    '@type': 'WebPage',
    '@id': `${url}#webpage`,
    url,
    name: title,
    description,
    inLanguage: lang,
    isPartOf: { '@id': WEBSITE_ID },
    breadcrumb: { '@id': `${url}#breadcrumb` },
    mainEntity: { '@id': `${url}#work` },
    ...(cover ? { primaryImageOfPage: { '@type': 'ImageObject', url: absolute(cover.src), width: cover.width, height: cover.height } } : {}),
  };

  return {
    title,
    description,
    ...(cover ? { image: absolute(cover.src), imageAlt: cover.alt, imageWidth: cover.width, imageHeight: cover.height } : {}),
    type: 'article',
    jsonLd: [website(t), personRef(t), page, work, breadcrumb],
  };
}

export function notFoundSeo(locale?: string): PageSeo {
  const t = useT(locale);
  return { title: t('seo.notFound.title'), description: t('seo.notFound.description'), noindex: true };
}
